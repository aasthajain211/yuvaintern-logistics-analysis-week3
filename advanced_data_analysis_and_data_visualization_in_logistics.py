# ====================================================
# TASK 3: ADVANCED DATA ANALYSIS & VISUALIZATION PIPELINE
# ====================================================

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

# Set professional plotting style
sns.set_theme(style="whitegrid")
plt.rcParams.update({'font.size': 11, 'figure.autolayout': True})

# ----------------------------------------------------
# STEP 1: LOAD SYNCHRONIZED PREPROCESSED DATA
# ----------------------------------------------------
np.random.seed(42)
data_size = 1000

data = {
    "Shipment_ID": [f"SHP_{1000+i}" for i in range(data_size)],
    "Origin_Hub": np.random.choice(["London", "Singapore", "Tokyo", "New York", "Rotterdam", "Shanghai"], data_size),
    "Transport_Mode": np.random.choice(["AIR", "OCEAN", "ROAD", "RAIL"], data_size),
    "Planned_Duration_Days": np.random.randint(2, 25, data_size),
    "Actual_Duration_Days": np.random.exponential(scale=6, size=data_size) + 2,
    "Shipment_Weight_KG": np.random.normal(loc=5000, scale=2000, size=data_size),
    "Delivery_Status": np.random.choice(["Delayed", "On-Time"], size=data_size, p=[0.25, 0.75])
}

df = pd.DataFrame(data)

# ----------------------------------------------------
# STEP 2: EXPLORATORY DATA ANALYSIS (EDA) - STATISTICAL SUMMARY
# ----------------------------------------------------
print("--- 1. Central Tendencies & Statistical Summary ---")
numeric_cols = ["Planned_Duration_Days", "Actual_Duration_Days", "Shipment_Weight_KG"]
summary_stats = df[numeric_cols].agg(['mean', 'median', 'std', 'min', 'max'])
print(summary_stats)

print("\n--- 2. Correlation Matrix ---")
corr_matrix = df[numeric_cols].corr()
print(corr_matrix)

# ----------------------------------------------------
# STEP 3: GENERATING & SHOWING VISUALIZATIONS IN COLAB
# ----------------------------------------------------

# Chart 1: Distribution of Actual vs Planned Delivery Durations
plt.figure(figsize=(10, 6))
sns.histplot(df['Actual_Duration_Days'], color='crimson', label='Actual Duration', kde=True, bins=30, alpha=0.5)
sns.histplot(df['Planned_Duration_Days'], color='dodgerblue', label='Planned Duration (SLA)', kde=True, bins=30, alpha=0.5)
plt.title('Figure 1: Comparative Distribution of Planned vs. Actual Transit Durations', fontsize=14, fontweight='bold')
plt.xlabel('Duration (Days)')
plt.ylabel('Shipment Frequency')
plt.legend()
plt.savefig('duration_distribution_comparison.png', dpi=300)
plt.show()  # Yeh graph ko screen par dikhayega

# Chart 2: Transport Mode vs Actual Duration (Boxplot)
plt.figure(figsize=(10, 6))
sns.boxplot(x='Transport_Mode', y='Actual_Duration_Days', hue='Transport_Mode', data=df, palette='Set2', legend=False)
plt.title('Figure 2: Transit Duration Variance Across Authorized Transport Modes', fontsize=14, fontweight='bold')
plt.xlabel('Transport Mode')
plt.ylabel('Actual Duration (Days)')
plt.savefig('transport_mode_bottlenecks.png', dpi=300)
plt.show()  # Yeh graph ko screen par dikhayega

# Chart 3: Correlation Heatmap of Numerical Logistics Metrics
plt.figure(figsize=(8, 6))
sns.heatmap(corr_matrix, annot=True, cmap='coolwarm', fmt=".2f", linewidths=0.5)
plt.title('Figure 3: Correlation Matrix of Supply Chain Metrics', fontsize=14, fontweight='bold')
plt.savefig('correlation_heatmap.png', dpi=300)
plt.show()  # Yeh graph ko screen par dikhayega

# Chart 4: Hub-wise Delay Frequency Analysis
plt.figure(figsize=(12, 6))
hub_delay = pd.crosstab(df['Origin_Hub'], df['Delivery_Status'], normalize='index') * 100
ax = hub_delay.plot(kind='bar', stacked=True, color=['#e74c3c', '#2ecc71'], figsize=(10, 6))
plt.title('Figure 4: Delivery Status Proportions Across Global Dispatch Hubs (%)', fontsize=14, fontweight='bold')
plt.xlabel('Origin Hub')
plt.ylabel('Percentage (%)')
plt.legend(title='Delivery Status')
plt.xticks(rotation=45)
plt.savefig('hub_delay_proportions.png', dpi=300)
plt.show()  # Yeh graph ko screen par dikhayega

